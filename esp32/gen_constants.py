"""Generate src/constants.h from the upstream protocol constants (fetched at build time, never committed)."""
import base64, json, re, sys, urllib.request
REV = "368a1f40008855a2f294a5de2b193828bde4d1b6"  # na-ji/pokemon-go-coin-bag, pinned (same as the add-on)
URL = f"https://raw.githubusercontent.com/na-ji/pokemon-go-coin-bag/{REV}/docs/protocol.js"
out = sys.argv[1]
src = sys.argv[2] if len(sys.argv) > 2 else None
text = open(src).read() if src else urllib.request.urlopen(URL, timeout=30).read().decode()
blob = "".join(re.search(r"const CONSTANTS = `(.*?)`;", text, re.S).group(1).split())
c = json.loads(base64.b64decode(blob))
u = c["UUIDS"]
lines = ["// generated by gen_constants.py - do not commit", "#pragma once"]
for k, name in (("advertisementService", "UUID_ADV"), ("gattService", "UUID_GATT"), ("readProtocol", "UUID_PROTOCOL"),
                ("readName", "UUID_NAME"), ("readMode", "UUID_MODE"), ("writeApplicationId", "UUID_APPID"),
                ("writeInitialNonce", "UUID_INITNONCE"), ("writeComplete", "UUID_COMPLETE"),
                ("writeFinalNonce", "UUID_FINALNONCE"), ("indicateData", "UUID_DATA"), ("indicateStage", "UUID_STAGE")):
    lines.append(f'#define {name} "{u[k].lower()}"')
lines.append(f'#define APP_ID_SUFFIX "{c["APPLICATION_ID_SUFFIX"]}"')
lines.append(f'#define APP_ID_WIDTH {int(c["APPLICATION_ID_GATT_WIDTH"])}')
lines.append(f'static const char RSA_N_HEX[] = "{c["RSA_MODULUS"]}";')
lines.append(f'static const char RSA_D_HEX[] = "{c["RSA_PRIVATE_EXPONENT"]}";')
lines.append(f'static const char DIGEST_PREFIX_HEX[] = "{c["SHA256_DIGEST_INFO_PREFIX"]}";')
open(out, "w").write("\n".join(lines) + "\n")
print("constants.h written")
